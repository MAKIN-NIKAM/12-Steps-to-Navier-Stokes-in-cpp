# Commented out IPython magic to ensure Python compatibility.

import numpy as np
import matplotlib.pyplot as plt
# %matplotlib inline

# Simulation Parameters
nx = 41         # no of grid points
dx = 2/(nx-1)   # grid spacing
#dt = 0.025      # time step size
dt = 0.5*dx/2    # from stability condition, dt <= 1*dx/u and max(u) = 2 m/s
nt = 20         # no of timesteps
print(dt)
# Initialization
u = np.ones(nx)                 # Array storing the final solution
u[int(0.5/dx):int(1/dx+1)] = 2  # Initializing with hat function
un = np.ones(nx) # initializing the place holder array
plt.plot(np.linspace(0,2,nx), u)
plt.show()

# Time step update

for n in range(nt):
  un = u.copy()
  for i in range(1,nx):
    u[i] = un[i] -un[i]*(dt/dx)*(un[i] - un[i-1])

plt.plot(np.linspace(0,2,nx), u)
plt.show()