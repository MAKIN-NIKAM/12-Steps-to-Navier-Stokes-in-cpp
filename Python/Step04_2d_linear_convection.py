# Commented out IPython magic to ensure Python compatibility.
from mpl_toolkits.mplot3d import Axes3D
import numpy as np
import matplotlib.pyplot as plt
from matplotlib import cm
# %matplotlib inline

# Variable Declarations

nx = 81
ny = 81
nt = 100
c = 1
dx = 2/(nx-1)
dy = 2/(nx-1)
sigma = 0.2
dt = sigma*dx

x = np.linspace(0,2,nx)
y = np.linspace(0,2,ny)

u = np.ones((ny,nx))
un = np.ones((ny,nx))

# Assign Initial Conditions

u[int(0.5/dy):int(1/dy + 1), int(0.5/dx):int(1/dx + 1)] = 2

# Plotting Initial Condition
fig = plt.figure(figsize=(11,7), dpi=100)   # Think of it as the canvas
ax = fig.add_subplot(111, projection ='3d')               # This is the area in the canvas where the fig is plotted
X,Y = np.meshgrid(x,y)                      # The 2D is created.
surf = ax.plot_surface(X,Y,u, cmap=cm.viridis)
plt.show()

# Time step update and Time integration

for n in range(nt):
  un = u.copy()
  u[1:-1,1:-1] = un[1:-1,1:-1] -c*(dt/dx)*(un[1:-1,1:-1] - un[1:-1,0:-2] ) - c*(dt/dy)*(un[1:-1,1:-1] - un[0:-2,1:-1] )

  u[0,:]  = 1
  u[-1,:] = 1
  u[:, 0] = 1
  u[:,-1] = 1

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection ='3d')
X,Y = np.meshgrid(x,y)
surf2 = ax.plot_surface(X,Y,u, cmap=cm.viridis)
plt.show()