# Convection-Diffusion Equation

import numpy as np
import sympy as sp
sp.init_printing(use_latex=True)

x, nu, t = sp.symbols('x nu t')
phi = sp.exp(-(x - 4*t)**2 /(4*nu*(t+1))) + sp.exp(-(x-4*t-2*sp.pi)**2 / (4*nu*(t+1)))
phi

"""**The sympy library helps us to calculate the derivatives and represent the inital condition easily**.

The above piece of code creates symbolic variables *x, nu, t*. These are not number-they are mathematical symbols. Like telling *Python treat x, nu, t as algebraic unknowns*.

"""

phiprime = phi.diff(x)
phiprime

u = -2*nu*phiprime/phi + 4
u

"""**Converting symbolic to numerical with lambdify**

**lambdify** converts the symbolic expression into a callable Python funciton, allowing you to pass actual numbers.
"""

ufunc = sp.lambdify((x,t,nu),u)
ufunc(3,1,1)

"""**Summary of Defining and representing the initial condition and analytical solution for Burger's Equation:**
1. x, nu, t   →   phi(x,t,nu)     
2. phiprime = dphi/dx                                        
3. u = -2*nu*(phiprime/phi) + 4                                        
4. lambdify → ufunc(x,t,nu)                         
5.   ufunc(x0, 0, nu) → numerical values                         
"""

# Commented out IPython magic to ensure Python compatibility.
import matplotlib.pyplot as plt
# %matplotlib inline
# Variable declaration
nx = 100
nt = 100
nu = 0.07
dx = 2*np.pi/(nx-1)
dt = dx*nu

x = np.linspace(0,2*np.pi, nx)
un = np.empty(nx)
u = np.array([ufunc(x0,0,nu) for x0 in x])
u

# Plotting Saw Tooth Function
plt.figure(figsize=(11,7.5))            # For better view of the figure
plt.plot(x,u, marker = 'o', lw=2)
plt.xlim([0,2*np.pi])
plt.ylim([0,10])
plt.xlabel('x')
plt.ylabel('u(x,0)')
plt.show()

# Time step update and Time integration
for n in range(nt):
  un = u.copy()
  for i in range(1,nx-1):
    u[i] = un[i] - un[i]*(dt/dx)*(un[i]-un[i-1]) + nu*(dt/dx**2)*(un[i+1] -2*un[i] + un[i-1])
  u[0] = un[0] -un[0]*(dt/dx)*(un[0]-un[-2]) + nu*(dt/dx**2)*(un[1]-2*un[0]+un[-2])
  u[-1]=u[0]        # Periodic Boundary Condition

u_analytical = np.array([ufunc(x0,nt*dt,nu) for x0 in x])

plt.figure(figsize=(11,7), dpi = 100)
plt.plot(x,u,'o-', lw=2, label='Computational')
plt.plot(x,u_analytical,'r-', lw=2, label='Analytical')
plt.xlim([0,2*np.pi])
plt.ylim([0,10])
plt.xlabel('x')
plt.ylabel('u(x,t)')
plt.legend()
plt.show()