# Commented out IPython magic to ensure Python compatibility.
from mpl_toolkits.mplot3d import Axes3D
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import cm
# %matplotlib inline

## Variable Declarations

nx = 101
ny = 101
nt = 80
dx = 2/(nx-1)
dy = 2/(ny-1)
sigma = 0.2
dt = sigma*dx

x = np.linspace(0,2,nx)
y = np.linspace(0,2,ny)

u = np.ones((ny,nx))
v = np.ones((ny,nx))
un = np.ones((ny,nx))
vn = np.ones((ny,nx))

# Assign Initial Conditions (The Hat Function)

u[int(0.5/dy) : int(1/dy +1), int(0.5/dx) : int(1/dx +1)] = 2
v[int(0.5/dy) : int(1/dy +1), int(0.5/dx) : int(1/dx +1)] = 2

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')

X, Y = np.meshgrid(x, y)
surf = ax.plot_surface(X, Y, v, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')

plt.show()

# Time step update and Time integration

for n in range(nt):
  un = u.copy()
  vn = v.copy()

  u[1:-1,1:-1] = un[1:-1,1:-1] -(dt/dx)*(un[1:-1,1:-1])*(un[1:-1,1:-1] - un[1:-1,0:-2]) - (dt/dy)*(vn[1:-1,1:-1])*(un[1:-1,1:-1] - un[0:-2,1:-1])

  v[1:-1,1:-1] = vn[1:-1,1:-1] -(dt/dx)*(un[1:-1,1:-1])*(vn[1:-1,1:-1] - vn[1:-1,0:-2]) - (dt/dy)*(vn[1:-1,1:-1])*(vn[1:-1,1:-1] - vn[0:-2,1:-1])

  u[0,:] = 1
  u[-1,:] = 1
  u[:,0] = 1
  u[:,-1] = 1

  v[0,:] = 1
  v[-1,:] = 1
  v[:,0] = 1
  v[:,-1] = 1

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')

X, Y = np.meshgrid(x, y)
surf1 = ax.plot_surface(X, Y, u, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')

plt.show()

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')

X, Y = np.meshgrid(x, y)
surf1 = ax.plot_surface(X, Y, v, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')

plt.show()