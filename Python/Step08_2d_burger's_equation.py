# Commented out IPython magic to ensure Python compatibility.
import numpy as np
from mpl_toolkits.mplot3d import Axes3D
import matplotlib.pyplot as plt
from matplotlib import cm
# %matplotlib inline

## Variable Declarations

nx = 41
ny = 41
nt = 120
c = 1
dx = 2/(nx-1)
dy = 2/(ny-1)
sigma = .0009
nu = 0.01
dt = sigma*dx*dy/nu

x = np.linspace(0,2,nx)
y = np.linspace(0,2,ny)

u = np.ones((ny,nx))
v = np.ones((ny,nx))
un = np.ones((ny,nx))
vn = np.ones((ny,nx))

# Assigning Initial Conditions

u[int(0.5/dy):int(1/dy+1),int(0.5/dx):int(1/dx + 1)] = 2
v[int(0.5/dy): int(1/dy+1), int(0.5/dx): int(1/dx+1)] = 2

# Plotting Initial Conditions
fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')
X,Y = np.meshgrid(x,y)
surf = ax.plot_surface(X, Y, u, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')
plt.show()

# Time integration & Time step update

for n in range(nt+1):

  un = u.copy()
  vn = v.copy()

  u[1:-1,1:-1] = un[1:-1,1:-1] - un[1:-1,1:-1]*(dt/dx)*(un[1:-1,1:-1] - un[1:-1,0:-2]) -vn[1:-1,1:-1]*(dt/dy)*(un[1:-1,1:-1] - un[0:-2,1:-1]) + (nu*dt/dx**2)*(un[1:-1,2:] - 2*un[1:-1,1:-1] + un[1:-1,0:-2]) + (nu*dt/dy**2)*(un[2:,1:-1] - 2*un[1:-1,1:-1] + un[0:-2,1:-1])

  v[1:-1,1:-1] = vn[1:-1,1:-1] - un[1:-1,1:-1]*(dt/dx)*(vn[1:-1,1:-1] - vn[1:-1,0:-2]) -vn[1:-1,1:-1]*(dt/dy)*(vn[1:-1,1:-1] - vn[0:-2,1:-1]) + (nu*dt/dx**2)*(vn[1:-1,2:] - 2*vn[1:-1,1:-1] + vn[1:-1,0:-2]) + (nu*dt/dy**2)*(vn[2:,1:-1] - 2*vn[1:-1,1:-1] + vn[0:-2,1:-1])

  u[0,:] = 1
  u[-1,:] = 1
  u[:,0] = 1
  u[:,-1] = 1

  v[0,:] = 1
  v[-1,:] = 1
  v[:,0] = 1
  v[:,-1] = 1

# Ploting the function

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')
X,Y = np.meshgrid(x,y)
surf = ax.plot_surface(X, Y, u, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')
plt.show()