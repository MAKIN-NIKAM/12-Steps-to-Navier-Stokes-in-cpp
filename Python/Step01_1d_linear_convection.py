# Commented out IPython magic to ensure Python compatibility.
import numpy as np
from matplotlib import pyplot
import time, sys

# %matplotlib inline

# Simulation Parameter
nx = 50       # nx is the no of grid points
dx = 2/(nx-1)        # dx is the grid spacing
nt = 25       # nt is the number of timesteps we want to calculate
dt = 0.025     # dt is the amount of time each timestep covers (delta t)
c = 1         # assuming wavespeed as 1

u = np.ones(nx)      # creates an array with all elements as one
u[int(0.5/dx):int(1/dx+1)] = 2  # sets u = 2 between 0.5 and 1 as per initial conditions
print(u)

pyplot.plot(np.linspace(0,2,nx), u)
pyplot.xlabel('x')
pyplot.ylabel('u(x,0)')
pyplot.show()

un = np.ones(nx)
for n in range(nt):
  un = u.copy()
  for i in range(1,nx):
    u[i] = un[i] - c * dt / dx * (un[i] - un[i-1])
print(u)

pyplot.plot(np.linspace(0,2,nx), u)
pyplot.xlabel('x')
pyplot.ylabel('u(x,0.625 s)')
pyplot.show()