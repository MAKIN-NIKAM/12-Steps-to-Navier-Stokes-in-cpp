# Commented out IPython magic to ensure Python compatibility.
from mpl_toolkits.mplot3d import Axes3D
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import cm
# %matplotlib inline

## Variable Declarations

nx = 31
ny = 31
nt = 17
dx = 2/(nx-1)
dy = 2/(ny-1)
sigma = 0.25
nu = 2
dt = (sigma*dx*dy)/nu
print(dt)


x = np.linspace(0,2,nx)
y = np.linspace(0,2,ny)

u = np.ones((ny,nx))
un = np.ones((ny,nx))

# Assign the initial conditions

u[int(0.5/dy):int(1/dy+1),int(0.5/dx):int(1/dx+1)] = 2

fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')

X, Y = np.meshgrid(x, y)
surf = ax.plot_surface(X, Y, u, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')

plt.show()

# Time step update and integration

def diffuse(nt):

    '''u[int(0.5/dy):int(1/dy+1),int(0.5/dx):int(1/dx+1)] = 2'''
    for n in range(nt):
      un = u.copy()

      u[1:-1,1:-1] = un[1:-1,1:-1] + nu*(dt/dx**2)*(un[1:-1,2:] - 2*un[1:-1,1:-1] + un[1:-1,0:-2]) + nu*(dt/dy**2)*(un[2:,1:-1] - 2*un[1:-1,1:-1] + un[0:-2,1:-1])

      u[0,:] = 1
      u[-1,:] = 1
      u[:,0] = 1
      u[:,-1] = 1


    fig = plt.figure(figsize=(11,7), dpi=100)
    ax = fig.add_subplot(111, projection='3d')
    X, Y = np.meshgrid(x, y)
    surf = ax.plot_surface(X, Y, u[:], rstride=1, cstride=1, cmap=cm.viridis,
        linewidth=0, antialiased=True)
    ax.set_xlabel('X')
    ax.set_ylabel('Y')
    plt.show()

diffuse(2000)

diffuse(3100)
print(dt)