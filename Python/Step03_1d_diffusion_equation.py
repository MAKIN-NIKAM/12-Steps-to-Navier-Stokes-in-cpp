import numpy as np
import matplotlib.pyplot as plt

# 1D Diffusion Equation

# Simulation Parameters

nx = 41
nt = 20
dx = 2/(nx-1)
nu = 1
sigma = 0.3
dt = (sigma*dx**2)/nu

# Initialization

u = np.ones(nx)
u[int(0.5/dx):int(1/dx+1)] = 2
un = np.ones(nx)
plt.plot(np.linspace(0,2,nx), u)
plt.xlabel('x')
plt.ylabel('u(x,0)')
plt.show()

# Time stepping

for n in range(nt):
  un = u.copy()
  for i in range(1,nx-1):
    u[i] = un[i] + nu*dt/dx**2*(un[i+1] -2*un[i] + un[i-1])

plt.plot(np.linspace(0,2,nx), u)
plt.xlabel('x')
plt.ylabel('u(x,t)')
plt.show()