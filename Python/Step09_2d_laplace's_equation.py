import numpy as np
from mpl_toolkits.mplot3d import Axes3D
import matplotlib.pyplot as plt
from matplotlib import cm


# Variable Declarations

nx = 101
ny = 101
dx = 2/(nx-1)
dy = 1/(ny-1)
c = 1/(2*(dx**2 + dy**2))
target = 1e-5

# Initialization

x = np.linspace(0,2,nx)
y = np.linspace(0,1,ny)

p = np.zeros((ny,nx))
pn = np.zeros((ny,nx))

p[:,0] = 0
p[:,-1] = y

p[0,:] = p[1,:]
p[-1,:] = p[-2,:]

print(p)

# Plotting Initial Conditions
fig = plt.figure(figsize=(11,7), dpi=100)
ax = fig.add_subplot(111, projection='3d')
X,Y = np.meshgrid(x,y)
surf = ax.plot_surface(X, Y, p, cmap=cm.viridis, rstride=2, cstride=2)
ax.set_xlabel('X')
ax.set_ylabel('Y')
plt.show()

# Numerical Integration

error = 1
target = 1e-4
iter_count = 0

while error > target:
    pn = p.copy()
    p[1:-1,1:-1] = c*(dy**2*(pn[1:-1,2:] + pn[1:-1,0:-2]) +
                       dx**2*(pn[2:,1:-1] + pn[0:-2,1:-1]))
    p[:,0]  = 0
    p[:,-1] = y
    p[0,:]  = p[1,:]
    p[-1,:] = p[-2,:]

    error = np.max(np.abs(p - pn))
    iter_count += 1

print('Iterations:', iter_count)  # how many did it run?
print('Final error:', error)
print('Max p:', p.max())          # what is max value?
print('Min p:', p.min())


print(p)

